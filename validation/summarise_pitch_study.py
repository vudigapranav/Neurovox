#!/usr/bin/env python3
"""Summarises docs/results/pitch_study.csv (written by the Java PitchStudy tool) into tables and a figure.

    .venv/bin/python validation/summarise_pitch_study.py

Outputs docs/results/pitch_study.md and docs/results/figures/pitch_study.png.
"""

import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "docs" / "results"


def pooled(group, prefix):
    frames = group[f"{prefix}_frames"].sum()
    if frames == 0:
        return {"frames": 0}
    return {
        "frames": int(frames),
        "mae_hz": float((group[f"{prefix}_mae_hz"] * group[f"{prefix}_frames"]).sum() / frames),
        "octave_error_rate": float(group[f"{prefix}_octave_errors"].sum() / frames),
        "gross_error_rate": float(group[f"{prefix}_gross_errors"].sum() / frames),
        "voicing_recall": float(group[f"{prefix}_voicing_recall"].mean()),
        "false_voicing": float(group[f"{prefix}_false_voicing"].mean()),
    }


def main():
    df = pd.read_csv(RESULTS / "pitch_study.csv")
    summary = {"files": int(df["file"].nunique()), "conditions": {}}
    for (condition, detector), g in df.groupby(["condition", "detector"], sort=False):
        entry = {"truth": pooled(g, "truth"), "ms_per_second_median": float(g["ms_per_second"].median())}
        if g["praat_frames"].notna().any():
            entry["praat"] = pooled(g.dropna(subset=["praat_frames"]), "praat")
        j = g.dropna(subset=["jitter_local"])
        entry["jitter_mae_vs_truth"] = float(np.mean(np.abs(j["jitter_local"] - j["true_jitter_local"]))) if len(j) else None
        entry["jitter_files_measured"] = int(len(j))
        summary["conditions"].setdefault(condition, {})[detector] = entry

    # How much the detector choice shifts jitter (same file, same condition).
    wide = df.pivot_table(index=["file", "condition"], columns="detector", values="jitter_local").dropna()
    shift = {}
    for condition, g in wide.groupby(level="condition"):
        diff = (g["yin"] - g["autocorrelation"]).abs()
        rel = diff / g["autocorrelation"]
        shift[condition] = {"files": int(len(g)), "mean_abs_shift": float(diff.mean()),
                            "median_relative_shift": float(rel.median()), "max_relative_shift": float(rel.max())}
    summary["jitter_shift_yin_vs_autocorrelation"] = shift
    (RESULTS / "pitch_study_summary.json").write_text(json.dumps(summary, indent=2) + "\n")

    lines = ["# Autocorrelation versus YIN (generated)", "",
             "Generated by `java ... com.neurovox.tools.PitchStudy` and `validation/summarise_pitch_study.py`. Do not edit by hand.", "",
             f"{summary['files']} synthetic sustained vowels × 3 conditions × 2 detectors. Errors are pooled over frames voiced in "
             "both the detector and the reference. Octave error = estimate within 5 % of half or double the reference; gross error = "
             "more than 20 % off. Time = median of 10 runs after 3 warm-up runs, per second of audio at 16 kHz, on the development "
             "laptop (Apple M4, Java 21). The truth reference is 1 / (length of the cycle containing the frame), which a windowed "
             "estimator cannot match exactly, so its MAE has a floor; the Praat reference is Praat's own To Pitch (ac).", "",
             "| Condition | Detector | MAE vs truth (Hz) | Octave errors | Gross errors | Voicing recall | False voicing in silence | MAE vs Praat (Hz) | ms per s of audio | Jitter MAE vs truth |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for condition, detectors in summary["conditions"].items():
        for detector, e in detectors.items():
            t = e["truth"]
            p = e.get("praat")
            lines.append(f"| {condition} | {detector} | {t['mae_hz']:.3f} | {100 * t['octave_error_rate']:.2f} % | "
                         f"{100 * t['gross_error_rate']:.2f} % | {100 * t['voicing_recall']:.1f} % | {100 * t['false_voicing']:.1f} % | "
                         f"{'—' if not p else f'{p['mae_hz']:.3f}'} | {e['ms_per_second_median']:.1f} | "
                         f"{'—' if e['jitter_mae_vs_truth'] is None else f'{100 * e['jitter_mae_vs_truth']:.3f} %-points'} |")
    lines += ["", "## Does the detector choice change jitter?", "",
              "Local jitter computed with pulses guided by each detector's contour (same file, same region, same pulse code):", "",
              "| Condition | Files | Mean absolute jitter shift | Median relative shift | Max relative shift |", "|---|---|---|---|---|"]
    for condition, s in shift.items():
        lines.append(f"| {condition} | {s['files']} | {100 * s['mean_abs_shift']:.4f} %-points | {100 * s['median_relative_shift']:.2f} % | "
                     f"{100 * s['max_relative_shift']:.1f} % |")
    lines.append("")
    (RESULTS / "pitch_study.md").write_text("\n".join(lines))
    figure(summary)
    print("\n".join(lines))


def figure(summary):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    conditions = list(summary["conditions"].keys())
    fig, axes = plt.subplots(1, 3, figsize=(13, 3.6))
    colors = {"autocorrelation": "#0F766E", "yin": "#B45309"}
    for ax, (metric, label, scale) in zip(axes, [("mae_hz", "MAE vs truth (Hz)", 1), ("octave_error_rate", "Octave errors (%)", 100),
                                                  ("gross_error_rate", "Gross errors (%)", 100)]):
        x = np.arange(len(conditions))
        for k, detector in enumerate(["autocorrelation", "yin"]):
            values = [summary["conditions"][c][detector]["truth"][metric] * scale for c in conditions]
            ax.bar(x + (k - 0.5) * 0.38, values, 0.38, label=detector, color=colors[detector])
        ax.set_xticks(x, conditions)
        ax.set_title(label, fontsize=10)
    axes[0].legend(fontsize=8)
    fig.suptitle("Autocorrelation vs YIN on 40 synthetic vowels", fontsize=11)
    fig.tight_layout()
    (RESULTS / "figures").mkdir(exist_ok=True)
    fig.savefig(RESULTS / "figures" / "pitch_study.png", dpi=150)


if __name__ == "__main__":
    main()
